let currentLang = 'es';

function applyTranslations(lang) {
  currentLang = lang;
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Update lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Update page title
  const titles = {
    es: 'Sumak Kawsay | Tours Amazónia – Espíritu de la Selva',
    en: 'Sumak Kawsay | Amazon Tours – Spirit of the Jungle',
    fr: 'Sumak Kawsay | Tours Amazonie – Esprit de la Forêt'
  };
  document.title = titles[lang] || titles.es;
}

// Init
document.addEventListener('DOMContentLoaded', () => {
  // Check browser language
  const browserLang = navigator.language.slice(0, 2);
  const initLang = ['es', 'en', 'fr'].includes(browserLang) ? browserLang : 'es';
  applyTranslations(initLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyTranslations(btn.getAttribute('data-lang')));
  });
});

window.applyTranslations = applyTranslations;
window.translations = translations;
