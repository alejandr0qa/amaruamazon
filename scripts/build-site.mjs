import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import crypto from "node:crypto";
import { parse, parseFragment, serialize } from "parse5";
import { siteUrl, languages, languagePaths, contactEmail } from "../site.config.mjs";
import { experiencePath, experienceCopy, experienceAlt, sceneAlt } from "../src/experience-pages.mjs";
import { buildExperiencePages } from "./build-experience-pages.mjs";

import { testimonials, renderTestimonials } from "../src/testimonials.mjs";
const root = path.resolve(import.meta.dirname, "..");
const read = (name) =>
  fs.readFileSync(path.join(root, name), "utf8").replace(/\r\n/g, "\n");
const template = read("src/index.template.html");
const data = vm.runInNewContext(
  read("src/translations.js") +
    "\n" +
    read("content.js") +
    "\n" +
    read("render.js") +
    "\n({translations,experiences,journeys,gallery,render:AmaruRender})",
);
const walk = function* (node) {
  yield node;
  for (const child of node.childNodes || []) yield* walk(child);
};
const attr = (node, key) => node.attrs?.find((a) => a.name === key)?.value;
const setAttr = (node, key, value) => {
  const existing = node.attrs.find((a) => a.name === key);
  if (existing) existing.value = String(value);
  else node.attrs.push({ name: key, value: String(value) });
};
const removeAttr = (node, key) => {
  node.attrs = node.attrs.filter((a) => a.name !== key);
};
const text = (node) =>
  node.nodeName === "#text"
    ? node.value
    : (node.childNodes || []).map(text).join("");
const setText = (node, value) => {
  node.childNodes = [
    { nodeName: "#text", value: String(value), parentNode: node },
  ];
};
const setHtml = (node, html) => {
  node.childNodes = parseFragment(html, { scriptingEnabled: false }).childNodes;
  node.childNodes.forEach((child) => {
    child.parentNode = node;
  });
};
const original = parse(template, { scriptingEnabled: false });
for (const node of walk(original)) {
  if (attr(node, "data-i18n"))
    data.translations.en[attr(node, "data-i18n")] = text(node).trim();
  for (const kind of ["alt", "aria", "placeholder"])
    if (attr(node, "data-i18n-" + kind))
      data.translations.en[attr(node, "data-i18n-" + kind)] = attr(
        node,
        kind === "aria" ? "aria-label" : kind,
      );
}
fs.writeFileSync(
  path.join(root, "i18n.js"),
  "// Generated by npm run build from src/translations.js and the English template.\nconst translations = " +
    JSON.stringify(data.translations, null, 2) +
    ";\n",
);
const version = crypto
  .createHash("sha256")
  .update(
    ["style.css", "main.js", "i18n.js", "content.js", "render.js", "experience.js", "media.js"]
      .map(read)
      .join("\n"),
  )
  .digest("hex")
  .slice(0, 12);
const languageUrl = (lang) => new URL(languagePaths[lang], siteUrl).href;

for (const lang of languages) {
  const doc = parse(template, { scriptingEnabled: false }),
    nodes = [...walk(doc)],
    base = lang === "en" ? "" : "../";
  const t = (key) => {
    const value = data.translations[lang][key];
    if (value === undefined)
      throw new Error(`Missing ${lang} translation: ${key}`);
    return value;
  };
  const find = (selector) => nodes.find(selector);
  const byId = (id) => find((n) => attr(n, "id") === id);
  const html = find((n) => n.tagName === "html");
  setAttr(html, "lang", lang);
  setAttr(html, "data-asset-base", base);
  for (const node of nodes) {
    if (attr(node, "data-i18n")) setText(node, t(attr(node, "data-i18n")));
    for (const kind of ["alt", "aria", "placeholder"])
      if (attr(node, "data-i18n-" + kind))
        setAttr(
          node,
          kind === "aria" ? "aria-label" : kind,
          t(attr(node, "data-i18n-" + kind)),
        );
    if (node.tagName === "title") setText(node, t("metaTitle"));
    if (attr(node, "name") === "description")
      setAttr(node, "content", t("metaDescription"));
    const property = attr(node, "property");
    if (property === "og:title") setAttr(node, "content", t("shareTitle"));
    if (property === "og:description")
      setAttr(node, "content", t("metaDescription"));
    if (property === "og:locale") setAttr(node, "content", t("ogLocale"));
    if (property === "og:url") setAttr(node, "content", languageUrl(lang));
    if (property === "og:image")
      setAttr(
        node,
        "content",
        new URL("assets/photos/amazon-river.webp", siteUrl).href,
      );
    if (attr(node, "name") === "twitter:title")
      setAttr(node, "content", t("shareTitle"));
    if (attr(node, "name") === "twitter:description")
      setAttr(node, "content", t("metaDescription"));
    if (attr(node, "name") === "twitter:image")
      setAttr(node, "content", new URL("assets/photos/amazon-river.webp", siteUrl).href);
    if (attr(node, "data-contact-email") !== undefined) {
      setAttr(node, "href", "mailto:" + contactEmail);
      setText(node, contactEmail);
    }
    if (attr(node, "rel") === "canonical")
      setAttr(node, "href", languageUrl(lang));
    if (attr(node, "hreflang"))
      setAttr(
        node,
        "href",
        languageUrl(
          attr(node, "hreflang") === "x-default"
            ? "en"
            : attr(node, "hreflang"),
        ),
      );
    if (attr(node, "type") === "application/ld+json") {
      const schema = JSON.parse(text(node));
      schema.url = siteUrl;
      schema["@id"] = new URL("#organization", siteUrl).href;
      schema.email = contactEmail;
      schema.logo = new URL("assets/brand/amaru-logo.webp", siteUrl).href;
      setText(node, JSON.stringify({
        "@context": "https://schema.org",
        "@graph": [schema, {
          "@type": "WebPage", "@id": languageUrl(lang) + "#webpage",
          url: languageUrl(lang), name: t("metaTitle"),
          description: t("metaDescription"), inLanguage: lang,
          about: { "@id": schema["@id"] },
        }],
      }));
    }
    for (const key of ["href", "src", "srcset", "data-src", "data-srcset"]) {
      const value = attr(node, key);
      if (value && (key === "srcset" || key === "data-srcset")) {
        setAttr(node, key, value.split(",").map((candidate) => {
          const [url, ...descriptor] = candidate.trim().split(/\s+/);
          return [ /^(?:[a-z]+:|#|\/)/i.test(url) ? url : base + url, ...descriptor ].join(" ");
        }).join(", "));
      } else if (value && !/^(?:[a-z]+:|#|\/)/i.test(value))
        setAttr(node, key, base + value.replace(/\?v=[^#]+/, ""));
    }
    if (node.tagName === "script" && attr(node, "src"))
      setAttr(node, "src", attr(node, "src") + "?v=" + version);
    if (node.tagName === "link" && attr(node, "href") === base + "style.css")
      setAttr(node, "href", base + "style.css?v=" + version);
    if (attr(node, "data-lang")) {
      const target = attr(node, "data-lang");
      node.tagName = "a";
      node.nodeName = "a";
      removeAttr(node, "aria-pressed");
      removeAttr(node, "aria-current");
      setAttr(
        node,
        "href",
        target === "en" ? base || "./" : base + languagePaths[target],
      );
      setAttr(node, "hreflang", target);
      if (target === lang) setAttr(node, "aria-current", "page");
    }
    if (attr(node, "data-quick-enquiry") !== undefined)
      setAttr(
        node,
        "href",
        "https://wa.me/573132560145?text=" +
          encodeURIComponent(t("hello") + "\n\n" + t("quickFallback")),
      );
  }
  const context = { ...data, lang, t, base,
    photoAlt: { ...experienceAlt, ...sceneAlt },
    pagePaths: Object.fromEntries(data.experiences.map((item) => [item.id, base + experiencePath(item.id, lang)])),
    fullExperienceLabel: experienceCopy[lang].full,
  };
  setHtml(byId("experience-grid"), data.render.experienceCards(context));
  const testimonialHtml = renderTestimonials(testimonials, lang, data.render.escape);
  if (testimonialHtml) {
    const faq = byId("travel-info");
    const section = parseFragment(testimonialHtml).childNodes[0];
    section.parentNode = faq.parentNode;
    faq.parentNode.childNodes.splice(faq.parentNode.childNodes.indexOf(faq), 0, section);
  }
  setText(byId("filter-status"), `${data.experiences.length} ${t("filterCount")}`);
  setHtml(byId("journey-content"), data.render.journeyPanels(context));
  setHtml(byId("gallery-grid"), data.render.galleryItems(context));
  setHtml(byId("interest"), data.render.interestOptions(context));
  setHtml(byId("quick-experiences"), data.render.quickChoices(context));
  setAttr(
    byId("guide-language").childNodes.find(
      (n) =>
        n.tagName === "option" &&
        attr(n, "value") ===
          { en: "English", es: "Español", fr: "Français" }[lang],
    ),
    "selected",
    "",
  );
  setAttr(
    byId("quick-send"),
    "href",
    "https://wa.me/573132560145?text=" +
      encodeURIComponent(t("hello") + "\n\n" + t("quickFallback")),
  );
  const output = path.join(root, languagePaths[lang], "index.html");
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(
    output,
    "<!-- Generated by npm run build. Edit src/index.template.html instead. -->\n" +
      serialize(doc).replace(/[\t ]+$/gm, "") +
      "\n",
  );
}
const experienceRoutes = buildExperiencePages({ root, data, version });
const sitemapGroups = [
  Object.fromEntries(languages.map((lang) => [lang, languagePaths[lang]])),
  ...data.experiences.map((item) => Object.fromEntries(languages.map((lang) => [lang, experiencePath(item.id, lang)]))),
];
fs.writeFileSync(
  path.join(root, "sitemap.xml"),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' +
    sitemapGroups.flatMap((group) => languages.map((lang) => {
      const alternates = [...languages, "x-default"].map((alternate) =>
        `    <xhtml:link rel="alternate" hreflang="${alternate}" href="${new URL(group[alternate === "x-default" ? "en" : alternate], siteUrl).href}"/>`,
      ).join("\n");
      return `  <url>\n    <loc>${new URL(group[lang], siteUrl).href}</loc>\n${alternates}\n  </url>`;
    }))
      .join("\n") +
    "\n</urlset>\n",
);
fs.writeFileSync(
  path.join(root, "robots.txt"),
  `User-agent: *\nAllow: /\nSitemap: ${new URL("sitemap.xml", siteUrl).href}\n`,
);
console.log(
  `Built ${languages.length} homepages and ${experienceRoutes.length} experience pages; asset version ${version}.`,
);
